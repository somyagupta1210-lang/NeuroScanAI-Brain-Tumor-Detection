"""PDF report generation (ReportLab)."""
import os
from datetime import datetime
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

PROJECT = "Brain Tumor Detection - AI Analysis Report"
DISCLAIMER = ("This report is generated by an AI-based research prototype. It is NOT a medical "
              "diagnosis. Please consult a qualified medical professional.")


def build_report(scan: dict, image_path: str, model_info: dict, out_path: str) -> str:
    ss = getSampleStyleSheet()
    title = ParagraphStyle("t", parent=ss["Title"], fontSize=20, textColor=colors.HexColor("#0A0A0A"))
    h = ParagraphStyle("h", parent=ss["Heading2"], textColor=colors.HexColor("#007A44"))
    body = ss["BodyText"]
    tumor = scan["prediction"] == "Tumor Detected"
    when = datetime.fromisoformat(scan["created_at"]).strftime("%d %B %Y, %I:%M %p")

    story = [Paragraph("BRAIN TUMOR DETECTION", title),
             Paragraph("AI Analysis Report", ParagraphStyle("s", parent=ss["Heading3"], alignment=1)),
             Spacer(1, 8 * mm)]

    rows = [["Scan ID", scan["scan_id"]], ["Date & Time", when], ["File", scan["filename"]],
            ["AI Prediction", scan["prediction"]],
            ["Model Confidence", f"{scan['confidence'] * 100:.1f}%"],
            ["Tumor Probability", f"{scan['tumor_probability'] * 100:.1f}%"]]
    t = Table(rows, colWidths=[45 * mm, 110 * mm])
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CCCCCC")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F0F0F0")),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("TEXTCOLOR", (1, 3), (1, 3), colors.HexColor("#C0392B") if tumor else colors.HexColor("#007A44")),
        ("FONTNAME", (1, 3), (1, 3), "Helvetica-Bold"),
        ("PADDING", (0, 0), (-1, -1), 6)]))
    story += [t, Spacer(1, 6 * mm), Paragraph("Uploaded MRI Image", h)]
    if os.path.exists(image_path):
        story.append(Image(image_path, width=70 * mm, height=70 * mm, kind="proportional"))

    story += [Spacer(1, 6 * mm), Paragraph("Model Information", h),
              Paragraph(f"Architecture: {model_info['name']}<br/>Input: {model_info['input']}<br/>"
                        f"Output: {model_info['output']}<br/>Mode: {model_info['mode']}", body)]
    if model_info["mode"] == "demo":
        story.append(Paragraph("<b>NOTE:</b> No trained model was loaded - this result is a demo placeholder.", body))
    story += [Spacer(1, 8 * mm), Paragraph("IMPORTANT DISCLAIMER", h), Paragraph(DISCLAIMER, body)]

    SimpleDocTemplate(out_path, pagesize=A4, title=PROJECT, leftMargin=20 * mm, rightMargin=20 * mm).build(story)
    return out_path
